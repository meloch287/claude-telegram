#!/usr/bin/env bash
#
# Сторож места на диске.
#
# На этой машине живут три десятка проектов, и место кончается незаметно: то
# кэш сборок докера разрастётся, то журналы. Кончится совсем - встанет всё
# сразу, и чинить придётся руками в неудобный момент.
#
# Чистим только то, что восстанавливается само. Тома docker не трогаем никогда:
# в них лежат чужие базы, и «неиспользуемый том» может оказаться нужным через
# час. Каталоги проектов и сборок тоже не наши - о них сторож только сообщает.
#
# Два уровня. Сперва заведомо безвредное: кэш сборок, журналы, кэши пакетных
# менеджеров. Если и после этого места мало - образы, к которым не привязан ни
# один контейнер и которым больше двух недель. Не помогло - зовём человека:
# дальше начинаются чужие данные, и решать должен он.
set -uo pipefail

MOUNT=${MOUNT:-/}
# Порог, ниже которого начинаем действовать.
MIN_GB=${MIN_GB:-5}
# Цель: чистим не до порога, а с запасом - иначе сторож будет срабатывать
# каждые пятнадцать минут и без конца дёргать докер.
TARGET_GB=${TARGET_GB:-12}
APP_DIR=${APP_DIR:-/opt/claude-telegram}
STATE_FILE=${STATE_FILE:-/var/lib/claude-telegram/disk-guard.state}

# shellcheck source=scripts/notify-owner.sh
source "$APP_DIR/scripts/notify-owner.sh"

mkdir -p "$(dirname "$STATE_FILE")"

free_gb() {
  df -BG --output=avail "$MOUNT" 2>/dev/null | tail -1 | tr -dc '0-9'
}

remember() { echo "$1" > "$STATE_FILE"; }
last_state() { [ -f "$STATE_FILE" ] && cat "$STATE_FILE" || echo ok; }

before=$(free_gb)
[ -z "$before" ] && { echo "не смог прочитать df"; exit 1; }

if [ "$before" -ge "$MIN_GB" ]; then
  # Отбой даём только если раньше тревожили: иначе чат превратится в ленту.
  if [ "$(last_state)" != "ok" ] && [ "$before" -ge "$TARGET_GB" ]; then
    notify "✅ Место на диске в порядке: свободно ${before} ГБ."
    remember ok
  fi
  echo "свободно ${before} ГБ, порог ${MIN_GB} — ничего не делаю"
  exit 0
fi

echo "свободно ${before} ГБ, это ниже порога ${MIN_GB} — чищу"

# ── Уровень первый: то, что пересоберётся само ──────────────────────────────
# Кэш сборок докера обычно и есть главный едок: на этой машине он доходил до
# 23 ГБ, из них половина мусора от прошлых образов.
docker builder prune -af > /dev/null 2>&1
# Журналы: оставляем последние двести мегабайт, этого хватает на разбор аварии.
journalctl --vacuum-size=200M > /dev/null 2>&1
apt-get clean > /dev/null 2>&1
rm -rf /root/.npm/_cacache 2>/dev/null
# Образы без единого контейнера — но только висячие, без тега: их не вернуть
# никаким «up», и никому они уже не принадлежат.
docker image prune -f > /dev/null 2>&1

after=$(free_gb)
echo "после безопасной чистки: ${after} ГБ"

# ── Уровень второй: образы, к которым не привязан ни один контейнер ─────────
if [ "$after" -lt "$TARGET_GB" ]; then
  echo "всё ещё мало — убираю образы старше двух недель, не занятые контейнерами"
  docker image prune -af --filter until=336h > /dev/null 2>&1
  after=$(free_gb)
  echo "после глубокой чистки: ${after} ГБ"
fi

freed=$((after - before))

if [ "$after" -lt "$MIN_GB" ]; then
  # Дальше только чужое: каталоги сборок в /root, проекты, тома. Решает человек.
  if [ "$(last_state)" != "critical" ]; then
    notify "‼️ Места на диске мало: ${after} ГБ свободно, чистка помогла лишь на ${freed} ГБ.

Безопасное уже вычищено. Дальше только то, что трогать без тебя нельзя:
каталоги сборок в /root (Flutter и Android оставляют по два-три гигабайта
каждый), тома docker, старые проекты. Посмотри: du -sh /root/* | sort -rh | head"
  fi
  remember critical
  exit 1
fi

notify "🧹 Место на диске подходило к концу: было ${before} ГБ, стало ${after} ГБ.

Вычищен кэш сборок docker, журналы и кэши пакетных менеджеров — всё это
пересоберётся само. Тома и каталоги проектов не тронуты."
remember cleaned
echo "готово: было ${before} ГБ, стало ${after} ГБ"
exit 0
